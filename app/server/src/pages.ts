export function seedPages(db: DB) {
  const insert = db.prepare('INSERT OR IGNORE INTO pages (slug, title, body) VALUES (?, ?, ?)')
  for (const p of drafts) insert.run(p.slug, p.title, p.body)
}

export function renderPage(db: DB, slug: string, site: string) {
  const page = db.prepare('SELECT slug, title, body, updated_at FROM pages WHERE slug = ?').get(slug) as
    | { slug: string; title: string; body: string; updated_at: string }
    | undefined
  if (!page) return null
  const shop = getSettings(db, 'shop')
  const pay = getSettings(db, 'payment')
  const fill: Record<string, string> = {
    recipient: pay.recipient,
    taxId: pay.taxId,
    phone: shop.viberPhone,
    telegram: shop.managerTelegram,
    site,
  }
  return { ...page, body: page.body.replace(/\{(\w+)\}/g, (m, key: string) => fill[key] ?? m) }
}

export function listPages(db: DB) {
  return db.prepare('SELECT slug, title, updated_at FROM pages ORDER BY rowid').all()
}

export function savePage(db: DB, slug: string, title: string, body: string) {
  const res = db.prepare("UPDATE pages SET title = ?, body = ?, updated_at = datetime('now') WHERE slug = ?").run(title.trim(), body, slug)
  if (!res.changes) fail(404, 'Сторінку не знайдено.')
}

export function rawPage(db: DB, slug: string) {
  const page = db.prepare('SELECT slug, title, body, updated_at FROM pages WHERE slug = ?').get(slug)
  if (!page) fail(404, 'Сторінку не знайдено.')
  return page
}
